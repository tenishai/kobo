class FakeAgent:
    """hello()/converse() return a canned or scripted reply and record every
    call received.

    `hello_error`, when set, makes `hello()` raise `ClientError(hello_error)`
    instead of replying — HelloStep is the pipeline's last step, so this is
    the seam for exercising a failure there (agent lands FAILED with
    `first_reply` still None) without needing a real a2a backend.

    `replies`, when given, is consumed one reply per `converse()` call, in
    order — for scripting a multi-turn conversation's agent side. Once it
    runs out (or when `replies` isn't given at all), `converse()` falls back
    to the single canned `reply`. `converse_error` is `hello_error`'s
    counterpart for the chat path: when set, `converse()` raises
    `ClientError(converse_error)` instead of replying.
    """

    def __init__(
        self,
        *,
        reply: str = "hello yourself",
        hello_error: str | None = None,
        replies: list[str] | None = None,
        converse_error: str | None = None,
    ):
        self._reply = reply
        self._hello_error = hello_error
        self._replies = list(replies) if replies is not None else None
        self._converse_error = converse_error
        self.calls: list[tuple[str, str, str]] = []
        self.converse_calls: list[tuple[str, str, list[ChatMessage]]] = []

    def hello(self, namespace: str, service: str, text: str) -> str:
        self.calls.append((namespace, service, text))
        if self._hello_error is not None:
            raise ClientError(self._hello_error)
        return self._reply

    def converse(self, namespace: str, service: str, messages: list[ChatMessage]) -> str:
        self.converse_calls.append((namespace, service, list(messages)))
        if self._converse_error is not None:
            raise ClientError(self._converse_error)
        if self._replies:
            return self._replies.pop(0)
        return self._reply


class FakeKubectl:
    """rollout_ok() returns a configurable, constant result and records calls
    (only rollout_ok's — deploy_env_names/deploy_service_account are DeployStep's
    live-spec verification reads, not the rollout wait itself, so they're kept
    off `.calls` to leave existing rollout_ok-only assertions unaffected).

    `env_names`/`service_accounts` are `{(namespace, deploy): value}` maps for
    deploy_env_names/deploy_service_account, keyed exactly like the real
    kubectl calls DeployStep makes. Both default, for any (namespace, deploy)
    not given an explicit entry, to the wired-happy-path shape — the wired
    model env present and a service account of `agent-<deploy>` — so tests
    that only care about rollout_ok (the pre-existing ones) get a DeployStep
    that verifies clean without configuring anything new.

    `images` (P2b) is the same kind of `{(namespace, deploy): image}` map for
    `deploy_image`, the knowledge module's delivery check
    (`pnyx_api.knowledge.delivery_state`). An unconfigured (namespace,
    deploy) pair defaults to `FAKE_DEPLOY_IMAGE_DEFAULT`, whose tag is the
    first 12 chars of `FakeGitHub`'s default `local_head_result` — so a test
    wiring bare `FakeGitHub()`/`FakeKubectl()` together sees a "delivered"
    state without configuring either fake.

    `apply_secret` (P2c) records every call into the dedicated
    `secrets_applied` list (deliberately NOT `.calls`, which this class's
    existing tests assert on exactly for `rollout_ok` alone — see above) as
    `(namespace, name, literals)`, so a `wire_slack` test can assert on the
    secret name/literals without any real kubectl involved. `apply_secret_error`,
    when set, raises `ClientError(apply_secret_error)` instead of recording
    — the seam for exercising `wire_slack`'s/the route's failure handling.
    """

    def __init__(
        self,
        *,
        rollout_result: bool = True,
        env_names: dict[tuple[str, str], list[str]] | None = None,
        service_accounts: dict[tuple[str, str], str] | None = None,
        images: dict[tuple[str, str], str] | None = None,
        apply_secret_error: str | None = None,
    ):
        self._rollout_result = rollout_result
        self._env_names = dict(env_names) if env_names else {}
        self._service_accounts = dict(service_accounts) if service_accounts else {}
        self._images = dict(images) if images else {}
        self._apply_secret_error = apply_secret_error
        self.calls: list[tuple[str, str]] = []
        self.secrets_applied: list[tuple[str, str, dict[str, str]]] = []

    def rollout_ok(self, namespace: str, deploy: str, timeout_s: int = 180) -> bool:
        self.calls.append((namespace, deploy))
        return self._rollout_result

    def deploy_env_names(self, namespace: str, deploy: str) -> list[str]:
        return self._env_names.get(
            (namespace, deploy), ["VERTEXAI_PROJECT", "VERTEXAI_LOCATION"]
        )

    def deploy_service_account(self, namespace: str, deploy: str) -> str:
        return self._service_accounts.get((namespace, deploy), f"agent-{deploy}")

    def deploy_image(self, namespace: str, deploy: str) -> str:
        return self._images.get((namespace, deploy), FAKE_DEPLOY_IMAGE_DEFAULT)

    def apply_secret(self, namespace: str, name: str, literals: dict[str, str]) -> None:
        if self._apply_secret_error is not None:
            raise ClientError(self._apply_secret_error)
        self.secrets_applied.append((namespace, name, dict(literals)))


