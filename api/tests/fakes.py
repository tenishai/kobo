class FakeGitHub:
    """Records repo creation/clones/pushes. `clone` materializes a realistic
    generated-scaffolding tree at `dest` (see the module-level templates
    above); `commit_push` replays a configurable sequence of bool results, so
    a test can make a second call return False (nothing to commit) without
    any real git diffing.

    CI-run behavior is keyed by commit sha, mirroring the real
    `runs_for_commit(repo, sha)` (never a repo-wide "latest"): `runs_by_sha`
    maps a sha to a *sequence of polls*, each poll itself the list of run
    dicts `runs_for_commit` would return that time (an empty list models CI
    registration lag — no run yet for that commit). Each sha's sequence holds
    at its last entry once exhausted, same replay convention as
    `commit_push_results`. `head_sha` answers with the fixed `head_sha` the
    fake was constructed with, unless `head_sha_sequence` is given, in which
    case each call returns the next entry (holding at the last one once
    exhausted — same replay convention as everything else here). BuildStep
    now resolves head_sha fresh on every poll (Fix 2: following an
    advancing head rather than pinning a stale read), so
    `head_sha_sequence` is how a test simulates the platform's setup-PR
    merge landing mid-poll — e.g. `["sha1", "sha1", "sha2"]` models two
    polls still seeing the pre-merge commit before the third sees the
    merge commit as head.

    `rerun(repo, run_id)` mirrors gh's real behavior of reusing the run's id
    rather than minting a new one: it records the call in `rerun_calls` and
    replaces whichever sha that run_id was last seen under with a fresh
    poll sequence, so a test can control what BuildStep sees on the polls
    right after the rerun fires. By default that's a single held-forever
    poll built from `rerun_result` (default a completed success) — enough
    for the plain heal case, or configure `rerun_result` to fail again to
    exercise the double-failure path. `rerun_followup`, when given, models a
    multi-poll sequence instead (one dict per poll, each merged with the run
    id, holding at the last entry once exhausted) — this is how a test
    simulates gh's read-after-write lag still echoing the stale pre-rerun
    payload for a poll or two before the real post-rerun result (e.g.
    queued, then completed) shows up.

    `knowledge_files` (P2b), when given, is a `{filename: content}` map that
    `clone` also materializes, under `bundle/knowledge/`, alongside the
    generated scaffolding above — this is how a test puts existing seed-memory
    files in the cloned repo for `kobo_api.knowledge.read_knowledge` (and
    friends) to find. Defaults to `None`, in which case `clone` writes no
    `bundle/knowledge/` tree at all (matching a real agent repo that has none
    yet) — every test that constructs a bare `FakeGitHub()` is unaffected by
    this knob's addition. `local_head_result` (P2b) is the fixed value
    `local_head(workdir)` returns — a real 40-hex sha shape by default,
    consistent with `FakeKubectl`'s default `deploy_image` tag (see
    `FAKE_LOCAL_HEAD_DEFAULT`/`FAKE_DEPLOY_IMAGE_DEFAULT` above) so the two
    fakes wired together read as "delivered" out of the box. Every call is
    recorded in both `calls` and the dedicated `local_head_calls` (the exact
    `workdir` it was given), so a test can assert it was called with the same
    workdir `commit_push` saw.

    `agent_yaml_transports` (P2c), when given, makes `clone` also write
    `bundle/agent.yaml` with `transports` set to exactly that list — the
    fixture `kobo_api.slack_setup.wire_slack`'s tests edit. Defaults to
    `None`, in which case `clone` writes no `bundle/agent.yaml` at all —
    matching a real agent repo's shape closely enough for existing tests
    (which predate this knob and assert bare `FakeGitHub()` writes no
    `bundle/` tree at all) while leaving every one of them unaffected: pass
    e.g. `[{"kind": "a2a", "host": "0.0.0.0", "port": 8080}]` (matching
    `kobo_api.composer`'s real rendering) for a wire_slack test that needs
    the file to exist. `gojira_secrets_from`, when given, adds a
    `secrets_from` key to the written `gojira.yaml` (absent by default,
    matching a real gojira.yaml that hasn't been through any
    `secrets_from`-writing edit yet) — the seam for testing that
    `wire_slack`'s edit appends to an existing list rather than clobbering
    it. `dockerfile_image`, defaulting to `FAKE_DOCKERFILE_OLD_IMAGE`, is the
    base image `clone` writes into a top-level `Dockerfile` (mirroring
    `kobo_api.composer`'s real template) — always written, unlike the
    knobs above, since every real agent repo has had a Dockerfile since it
    was first composed; the runtime-bump fixture `wire_slack`'s
    `_update_dockerfile_runtime_image` edit rewrites the FROM line of.

    `intake_files` (Task 3), when given, is a `{filename: content}` map that
    `clone` also materializes, under `bundle/intake/` — same idiom as
    `knowledge_files` above, for `kobo_api.intake.list_intake`/
    `delete_intake_file` to find existing one-shot upload files in the
    cloned repo. Defaults to `None` (no `bundle/intake/` tree at all,
    matching a real agent repo that's never had an upload).

    `tooling_files` (Tooling staged door), when given, is a `{filename:
    content}` map materialized under `bundle/tools/` — same idiom as
    `intake_files`, for `kobo_api.tooling.list_tooling`/`delete_tooling_file`
    to find existing uploaded/imported tooling files in the cloned agent
    repo. Defaults to `None` (no `bundle/tools/` tree at all).

    `tooling_source_files` (Tooling staged door), when given, maps a SOURCE
    repo's full name to a `{relative_path: content}` map (content may be
    `str`, UTF-8 encoded on write, or raw `bytes` — the latter is how a test
    seeds a candidate file that ISN'T valid UTF-8, for
    `kobo_api.tooling.import_tooling`'s decode-failure path) that `clone`
    also materializes at that path, parent dirs created as needed. This is
    keyed by repo (not layered onto `tooling_files`/the generic scaffolding
    above) because `import_tooling` clones a repo distinct from the agent's
    own — a plain `acme/tools-library`-shaped fixture, say — via this exact
    same `FakeGitHub`; a test builds one fake and calls `clone` on it twice
    (once per repo), and this knob only ever fires for the repo name(s) it
    names, leaving the agent repo's own clone (and every pre-existing test)
    completely unaffected. Defaults to `None` (no extra files for any repo).

    `intake_commit_shas`, `rev_parse_results`, and `ancestor_pairs` (Task 3)
    together model the three new GhCLI-only methods `kobo_api.intake.
    list_intake` calls (`commit_shas_for_paths`, `rev_parse_prefix`,
    `is_ancestor`) — none of which have any other caller, so unlike every
    other knob above, there's no "generic clone-time content" to fake: each
    is a direct lookup table.

    `intake_commit_shas` maps a path exactly as `list_intake` builds it
    (`"bundle/intake/<filename>"`) to the commit sha `commit_shas_for_paths`
    should report as that file's last-touch commit; a path not in the map
    defaults to `local_head_result` (`FAKE_LOCAL_HEAD_DEFAULT` by default) —
    "this file was last touched at the repo's own current head", the
    natural default for a file a test didn't bother giving its own commit.

    `rev_parse_results` maps a prefix string (as `list_intake` passes it —
    the live image's tag) to the full sha `rev_parse_prefix` should resolve
    it to, or explicitly `None` for "does not resolve". A prefix not in the
    map falls back to a small real-git-like heuristic: resolves to
    `local_head_result` if `local_head_result` starts with it (the tag
    naturally derived from `FAKE_DEPLOY_IMAGE_DEFAULT`, whose tag IS
    `FAKE_LOCAL_HEAD_DEFAULT`'s own first 12 chars, resolves this way with
    no configuration needed), otherwise `None` — so a garbage/non-hex tag
    (e.g. "latest") safely resolves to `None` by default, matching the real
    GhCLI's never-raises contract, without a test needing to spell that out.

    `ancestor_pairs` is a `{(ancestor, descendant)}` set of non-equal pairs
    `is_ancestor` should report `True` for beyond the automatic equality
    case (`is_ancestor(x, x)` is always `True` here, mirroring git's own
    `merge-base --is-ancestor` semantics, with no knob needed for it).
    Defaults to empty — so two different, unconfigured shas read as "not
    proven an ancestor" (pending), the conservative default.

    Together, the defaults above mean a bare `FakeGitHub(intake_files=...)`/
    `FakeKubectl()` pair reads every intake file as "ingested" out of the
    box (the same "wired happy path needs no configuration" property as
    `FAKE_LOCAL_HEAD_DEFAULT`/`FAKE_DEPLOY_IMAGE_DEFAULT` give
    `delivery_state`) — a test overrides one or more of these three knobs
    only to exercise a genuinely different (pending, or ancestor-but-not-
    equal) case.

    `org_yaml` (Task 2), when given, makes `clone` also write a top-level
    `org.yaml` with exactly that text — the fixture `kobo_api.org.
    load_org_config`'s tests use to control what a cloned kobo-config repo's
    org.yaml contains. Defaults to `None`, in which case `clone` writes no
    `org.yaml` at all (matching every other repo, none of which have ever
    had one). `clone_error`, when set, makes `clone` raise
    `ClientError(clone_error)` instead of writing anything — the seam for
    exercising a caller's clone-failure handling (e.g. `load_org_config`'s
    unwired-on-`ClientError` path) without a real git/gh subprocess. The
    call is still recorded in `.calls`/`.cloned` first, same as every other
    call here, before the error is raised.

    `track_pushed_content` (Task 7), when True, makes `create_repo_from_dir`
    snapshot every file under `src` (read at call time, before the caller's
    own tmpdir is cleaned up) into a per-repo store; `clone` for a repo with
    such a snapshot writes back exactly those files (nothing else — the
    synthetic gojira scaffolding below is skipped entirely for that repo)
    instead of synthesizing the generated-agent-repo tree. Defaults to
    `False`, so every pre-existing test (the whole agent-repo pipeline, whose
    `clone()` calls deliberately model "what gojira's own onboarding left in
    the repo", NOT a replay of whatever kobo itself pushed) is unaffected —
    this is purely for Task 7's bootstrap, which pushes/clones repos (the
    org-config repo, an org's skills repo) gojira never touches at all, so a
    faithful "clone reflects exactly what was last pushed" model is the
    right one there instead. `pr_url`, `open_pr`'s canned return value
    (Task 7), and `open_pr_calls`, the exact-argument recording for it, are
    documented on `open_pr` itself below.

    `open_prs` (Task 7 live-incident fix), when given, seeds `find_pr`'s
    open-PR map: keys are `f"{repo}#{branch}"`, values the PR URL `find_pr`
    should report as already open for that repo/branch pair. Defaults to
    `None` (no PR open anywhere), so every pre-existing test — which
    predates `find_pr` entirely — is unaffected. `open_pr` itself also
    writes into this same map (keyed off the `repo`/`branch` it was called
    with, valued with the fake's own `pr_url`) the moment it's called, so a
    single fake run through bootstrap twice reproduces the incident shape
    exactly: run 1's `open_pr` registers the PR, and run 2's `find_pr` sees
    it there without either being configured explicitly.

    `agent_card` (persona-metadata plan, Task 3), when given, is the exact
    dict `clone` writes (JSON-dumped, `indent=2`) to `bundle/agent-card.json`
    — always written (like `dockerfile_image` above, unlike every
    knob-gated file below it), since every real agent repo has had one
    since it was first composed (`kobo_api.composer.compose` always writes
    it). Defaults to `None`, in which case `clone` writes a card shaped
    like the one `kobo_api.composer._agent_card` baked before issue #147
    (placeholder description and version, `capabilities: []`, empty skills,
    `metadata: {"team": None, "purpose_tags": [], "capability": ""}`), so
    every write that refreshes the card is also exercised against an old
    card. This is what `kobo_api.metadata.commit_card_metadata`'s tests
    (and every step/route test whose HelloStep tail or PATCH/Regenerate
    call reaches `update_agent_card_metadata`) clone and edit in place.

    `clone_tree` (marketplace repo door, Task 1), when given, is a
    `{relpath: content}` map `clone` writes VERBATIM at `dest` instead of
    the generated-agent-repo scaffolding above -- the seam for a fake that
    stands in for a wholly different kind of repo (the org's marketplace
    tools/skills tree, not an agent's own bundle repo), the same
    "this knob replaces the generic scaffolding entirely" posture
    `track_pushed_content`'s `_pushed_content` branch already takes above
    it. Defaults to `None`, so every pre-existing test (all of which clone
    an agent repo) is unaffected. Every `commit_push` call snapshots the
    CURRENT content of `workdir` (same synchronous read-now discipline as
    `_snapshot_pushed_content`, since a caller's tempdir is typically gone
    the moment the call that pushed it returns) into `_pushed_trees`; the
    two test-only helpers below read off the most recent snapshot:
    `pushed_file(relpath)` returns that path's content (decoded UTF-8), and
    `push_count` is how many times `commit_push` has been called -- e.g. a
    validate-then-commit ordering assertion (`push_count == 0`) after a
    validation failure that raised before ever cloning.

    `rename_repo`/`archive_repo` (Task 3: agent destruction's repo step)
    mirror the real `GhCLI`'s own not-found contract: calling either
    against a `repo` not currently in `.repos` raises `ClientError("repo
    not found: {repo}")` with no knob needed — the same shape a real 404
    maps to. A successful `rename_repo` moves the entry in `.repos` from
    the old owner/name to `{owner}/{new_name}` and records the mapping in
    `.renamed` (old repo -> new repo, so a test can assert what a repo
    was renamed TO); a successful `archive_repo` adds `repo` to
    `.archived`. Every call (successful or not) is also recorded into
    `.rename_calls`/`.archive_calls` (the exact arguments given).
    `rename_error`/`archive_error`, when set, make the matching method
    raise `ClientError(that message)` INSTEAD of the not-found check or
    the real rename/archive — the seam for exercising a destroy step's
    handling of a non-404 failure (e.g. the real GitHub 403 an
    already-archived repo's PATCH returns, which this fake does not model
    structurally since `GhCLI` itself doesn't special-case it either — see
    `archive_repo`'s Protocol docstring).
    """

    def __init__(
        self,
        *,
        existing_repos: set[str] | None = None,
        commit_push_results: list[bool] | None = None,
        head_sha: str = "deadbeef",
        head_sha_sequence: list[str] | None = None,
        runs_by_sha: dict[str, list[list[dict]]] | None = None,
        rerun_result: dict | None = None,
        rerun_followup: list[dict] | None = None,
        knowledge_files: dict[str, str] | None = None,
        local_head_result: str = FAKE_LOCAL_HEAD_DEFAULT,
        agent_yaml_transports: list[dict] | None = None,
        gojira_secrets_from: list[str] | None = None,
        dockerfile_image: str = FAKE_DOCKERFILE_OLD_IMAGE,
        org_yaml: str | None = None,
        clone_error: str | None = None,
        track_pushed_content: bool = False,
        pr_url: str = "https://github.com/acme-corp/example-org-skills/pull/1",
        open_prs: dict[str, str] | None = None,
        existing_branches: set[str] | None = None,
        merge_pr_results: list[bool] | None = None,
        intake_files: dict[str, str] | None = None,
        intake_commit_shas: dict[str, str] | None = None,
        rev_parse_results: dict[str, str | None] | None = None,
        ancestor_pairs: set[tuple[str, str]] | None = None,
        tooling_files: dict[str, str] | None = None,
        tooling_source_files: dict[str, dict[str, str | bytes]] | None = None,
        rename_error: str | None = None,
        jobs_by_run: dict[int, list[dict]] | None = None,
        run_jobs_error: Exception | None = None,
        archive_error: str | None = None,
        agent_card: dict | None = None,
        clone_tree: dict[str, str] | None = None,
        extra_clone_files: dict[str, str] | None = None,
        repo_access_error: str | None = None,
        repo_files: dict[str, str] | None = None,
        branch_files: dict[str, dict[str, str]] | None = None,
        comparisons: dict[str, BranchComparison] | None = None,
        root_entries: list[str] | None = None,
        can_write: bool = True,
        default_branch: str = "main",
        protected_branches: set[str] | None = None,
        installation_repos: list[InstallationRepo] | None = None,
        installation_repos_error: str | None = None,
    ):
        self.repos: set[str] = set(existing_repos) if existing_repos else set()
        self._rename_error = rename_error
        self._archive_error = archive_error
        self.renamed: dict[str, str] = {}
        self.archived: set[str] = set()
        self.rename_calls: list[tuple[str, str]] = []
        self.archive_calls: list[str] = []
        self.created_from_dir: list[tuple[str, Path]] = []
        self.cloned: list[tuple[str, Path]] = []
        self.pushes: list[tuple[Path, str]] = []
        self.calls: list[str] = []
        self._track_pushed_content = track_pushed_content
        self._pushed_content: dict[str, dict[str, bytes]] = {}
        self._pr_url = pr_url
        self.open_pr_calls: list[dict] = []
        self.deleted_branches: list[tuple[str, str]] = []
        self.close_pr_calls: list[tuple[str, str, str]] = []
        self._comparisons = dict(comparisons or {})
        self._open_prs: dict[str, str] = dict(open_prs) if open_prs else {}
        self._existing_branches: set[str] = (
            set(existing_branches) if existing_branches else set()
        )
        # A pull request open from a branch means that branch is there.
        # Seeded rather than left to each caller so a test that models an
        # open request never also has to remember to model its head, and
        # so `branch_exists`/`compare` answer what the repository would.
        self._existing_branches.update(self._open_prs)
        self.merge_pr_calls: list[tuple[str, str]] = []
        self._merge_pr_results = (
            list(merge_pr_results) if merge_pr_results else [True]
        )
        self._merge_pr_index = 0
        self._commit_push_results = list(commit_push_results) if commit_push_results else [True]
        self._commit_push_index = 0
        self._knowledge_files = dict(knowledge_files) if knowledge_files else None
        self._local_head_result = local_head_result
        self._agent_yaml_transports = (
            list(agent_yaml_transports) if agent_yaml_transports is not None else None
        )
        self._gojira_secrets_from = (
            list(gojira_secrets_from) if gojira_secrets_from is not None else None
        )
        self._dockerfile_image = dockerfile_image
        self._org_yaml = org_yaml
        self._clone_error = clone_error
        self.local_head_calls: list[Path] = []
        self._intake_files = dict(intake_files) if intake_files else None
        self._intake_commit_shas = dict(intake_commit_shas) if intake_commit_shas else {}
        self._rev_parse_results = dict(rev_parse_results) if rev_parse_results else {}
        self._ancestor_pairs = set(ancestor_pairs) if ancestor_pairs else set()
        self._tooling_files = dict(tooling_files) if tooling_files else None
        self._tooling_source_files = (
            {repo: dict(files) for repo, files in tooling_source_files.items()}
            if tooling_source_files
            else {}
        )
        self._agent_card = dict(agent_card) if agent_card is not None else None
        self._clone_tree = dict(clone_tree) if clone_tree is not None else None
        self._extra_clone_files = (
            dict(extra_clone_files) if extra_clone_files is not None else None
        )
        self._pushed_trees: list[dict[str, bytes]] = []

        self._head_sha = head_sha
        self._head_sha_sequence = list(head_sha_sequence) if head_sha_sequence else None
        self._head_sha_index = 0
        self._runs_by_sha: dict[str, list[list[dict]]] = {
            sha: [list(poll) for poll in sequence]
            for sha, sequence in (runs_by_sha or {}).items()
        }
        if not self._runs_by_sha:
            # Default: the fake's own head_sha already has one CI run that's
            # completed successfully — the plain happy path.
            self._runs_by_sha[head_sha] = [
                [{"id": 1, "status": "completed", "conclusion": "success"}]
            ]
        self._run_index_by_sha: dict[str, int] = {}
        self._run_id_to_sha: dict[int, str] = {}
        self._repo_access_error = repo_access_error
        self._branch_files = (
            {branch: dict(files) for branch, files in branch_files.items()}
            if branch_files
            else {}
        )
        self._repo_files = (
            dict(repo_files)
            if repo_files is not None
            else {"Dockerfile": FAKE_CONNECTED_DOCKERFILE}
        )
        self._root_entries = (
            list(root_entries) if root_entries is not None else list(FAKE_CONNECTED_ROOT)
        )
        self._can_write = can_write
        self._default_branch = default_branch
        self._protected_branches: set[str] = (
            set(protected_branches) if protected_branches else set()
        )
        self._installation_repos = (
            list(installation_repos) if installation_repos is not None else None
        )
        self._installation_repos_error = installation_repos_error
        self._rerun_result = rerun_result or {"status": "completed", "conclusion": "success"}
        self._rerun_followup = list(rerun_followup) if rerun_followup else None
        self.rerun_calls: list[tuple[str, int]] = []
        # What `run_jobs` answers per run id: the jobs of that run with their
        # steps, the shape `gh run view --json jobs` gives once normalized.
        # Unscripted runs answer an empty list; `run_jobs_error` makes every
        # read raise, for the step's own fallback wording.
        self._jobs_by_run: dict[int, list[dict]] = dict(jobs_by_run or {})
        self._run_jobs_error = run_jobs_error

    def repo_exists(self, repo: str) -> bool:
        self.calls.append(f"repo_exists:{repo}")
        return repo in self.repos

    def repo_access(self, repo: str) -> RepoAccessInfo:
        """Visibility comes from `existing_repos`, exactly as `repo_exists`
        reads it, so one knob answers both. `can_write` and `default_branch`
        are their own knobs, defaulting to the wired happy path; a repo the
        fake has never heard of is invisible and carries none of them.

        Resolved case-insensitively, answering with the spelling
        `existing_repos` holds -- which is what GitHub itself does, and
        what the room's canonical-name handling is written against.
        """
        self.calls.append(f"repo_access:{repo}")
        # `repo_access_error` is how a test models GitHub itself being
        # unreachable, as opposed to answering "no such repository": the
        # real client raises there rather than reporting a finding.
        if self._repo_access_error is not None:
            raise ClientError(self._repo_access_error)
        known = {existing.lower(): existing for existing in self.repos}
        full_name = known.get(repo.lower())
        if full_name is None:
            return RepoAccessInfo(visible=False, can_write=False, default_branch="")
        return RepoAccessInfo(
            visible=True,
            can_write=self._can_write,
            default_branch=self._default_branch,
            full_name=full_name,
        )

    def read_file(self, repo: str, path: str, ref: str | None = None) -> str | None:
        """Whatever `repo_files` holds at `path`, None otherwise -- the same
        "nothing to read" the real client answers for a missing, oversized
        or non-file path. Not keyed by repo: every test here scans one.

        `ref` reads from `branch_files` instead, a `{branch: {path: text}}`
        map -- what a PROPOSED change contains, as opposed to what is
        merged. A branch with no entry there answers None for every path,
        which is the honest stand-in for a branch that does not exist.
        """
        self.calls.append(f"read_file:{repo}:{path}" + (f"@{ref}" if ref else ""))
        if ref is not None:
            return self._branch_files.get(ref, {}).get(path)
        return self._repo_files.get(path)

    def list_root(self, repo: str) -> list[str]:
        self.calls.append(f"list_root:{repo}")
        return list(self._root_entries)

    def list_installation_repos(self) -> list[InstallationRepo]:
        """Whatever `installation_repos` holds. Unset, it is derived from
        `existing_repos` -- one knob still answers the common case, and a
        test that cares about archived, private or pushed_at passes the
        list itself.

        `installation_repos_error` models GitHub refusing the question
        (the real client raises there rather than answering an empty
        installation).
        """
        self.calls.append("list_installation_repos")
        if self._installation_repos_error is not None:
            raise ClientError(self._installation_repos_error)
        if self._installation_repos is not None:
            return list(self._installation_repos)
        return [
            InstallationRepo(
                full_name=repo,
                archived=False,
                private=True,
                default_branch=self._default_branch,
                pushed_at="",
            )
            for repo in sorted(self.repos)
        ]

    def branch_protected(self, repo: str, branch: str) -> bool:
        """True for any branch named in `protected_branches`. Default empty:
        the room can merge its own wiring pull request.
        """
        self.calls.append(f"branch_protected:{repo}:{branch}")
        return branch in self._protected_branches

    def _snapshot_pushed_content(self, repo: str, src: Path) -> None:
        """Read every file under `src` now, synchronously — the real
        caller's tmpdir (Task 7's bootstrap, notably) is typically deleted
        the moment the call that invoked this returns, so this is the only
        chance to snapshot what was actually pushed. No-op unless the fake
        was constructed with `track_pushed_content=True`.
        """
        if not self._track_pushed_content:
            return
        self._pushed_content[repo] = {
            p.relative_to(src).as_posix(): p.read_bytes() for p in src.rglob("*") if p.is_file()
        }

    def create_repo_from_dir(self, repo: str, src: Path) -> None:
        self.calls.append(f"create_repo_from_dir:{repo}")
        self.created_from_dir.append((repo, src))
        self.repos.add(repo)
        self._snapshot_pushed_content(repo, src)

    def clone(self, repo: str, dest: Path) -> None:
        self.calls.append(f"clone:{repo}")
        self.cloned.append((repo, dest))
        if self._clone_error is not None:
            raise ClientError(self._clone_error)

        if self._clone_tree is not None:
            # A wholly different repo shape (the marketplace tree, not an
            # agent's own bundle repo) -- writes exactly this, nothing else
            # (class docstring's `clone_tree` entry).
            for rel_path, content in self._clone_tree.items():
                target = dest / rel_path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
            return

        if repo in self._pushed_content:
            # A repo tracked via `track_pushed_content`: model this clone as
            # exactly what was last pushed to it, nothing more — the generic
            # generated-agent-repo scaffolding below deliberately does not
            # apply (see the class docstring).
            for rel_path, data in self._pushed_content[repo].items():
                target = dest / rel_path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
            return

        name = _app_name_from_repo(repo)
        base = dest / "k8s" / "base"
        base.mkdir(parents=True, exist_ok=True)

        gojira_yaml_text = GOJIRA_YAML_TEMPLATE.format(name=name)
        if self._gojira_secrets_from is not None:
            gojira_data = yaml.safe_load(gojira_yaml_text)
            gojira_data["secrets_from"] = list(self._gojira_secrets_from)
            gojira_yaml_text = yaml.safe_dump(gojira_data, sort_keys=False)
        (dest / "gojira.yaml").write_text(gojira_yaml_text)

        (base / "deployment.yaml").write_text(DEPLOYMENT_YAML_TEMPLATE.format(name=name))
        (base / "service.yaml").write_text(SERVICE_YAML_TEMPLATE.format(name=name))
        (base / "podmonitoring.yaml").write_text(PODMONITORING_YAML_TEMPLATE.format(name=name))
        (base / "rules.yaml").write_text(RULES_YAML_TEMPLATE.format(name=name))
        (base / "kustomization.yaml").write_text(KUSTOMIZATION_YAML_TEMPLATE.format(name=name))

        (dest / "Dockerfile").write_text(DOCKERFILE_TEMPLATE.format(image=self._dockerfile_image))

        if self._org_yaml is not None:
            (dest / "org.yaml").write_text(self._org_yaml)

        bundle_dir = dest / "bundle"
        bundle_dir.mkdir(parents=True, exist_ok=True)
        card_data = (
            dict(self._agent_card)
            if self._agent_card is not None
            else {
                "name": name,
                "description": "Assembled by kobo.",
                "version": "0.1.0",
                "capabilities": [],
                "skills": [],
                "metadata": {"team": None, "purpose_tags": [], "capability": ""},
            }
        )
        (bundle_dir / "agent-card.json").write_text(json.dumps(card_data, indent=2) + "\n")

        if self._agent_yaml_transports is not None:
            bundle_dir.mkdir(parents=True, exist_ok=True)
            agent_yaml_data = {"name": name, "transports": list(self._agent_yaml_transports)}
            (bundle_dir / "agent.yaml").write_text(
                yaml.safe_dump(agent_yaml_data, sort_keys=False)
            )

        if self._knowledge_files:
            knowledge_dir = bundle_dir / "knowledge"
            knowledge_dir.mkdir(parents=True, exist_ok=True)
            for filename, content in self._knowledge_files.items():
                (knowledge_dir / filename).write_text(content)

        if self._intake_files:
            intake_dir = bundle_dir / "intake"
            intake_dir.mkdir(parents=True, exist_ok=True)
            for filename, content in self._intake_files.items():
                (intake_dir / filename).write_text(content)

        if self._tooling_files:
            tools_dir = bundle_dir / "tools"
            tools_dir.mkdir(parents=True, exist_ok=True)
            for filename, content in self._tooling_files.items():
                (tools_dir / filename).write_text(content)

        if repo in self._tooling_source_files:
            for rel_path, content in self._tooling_source_files[repo].items():
                target = dest / rel_path
                target.parent.mkdir(parents=True, exist_ok=True)
                raw = content.encode("utf-8") if isinstance(content, str) else content
                target.write_bytes(raw)

        self._write_extra_clone_files(dest)

    def _write_extra_clone_files(self, dest: Path) -> None:
        """Lay `extra_clone_files` over the generated tree, last, so a test
        can add a file the scaffolding has no knob for (a team's own
        serviceaccount.yaml) or replace one wholesale (a gojira.yaml that
        already carries env of its own). `clone_tree`, by contrast,
        REPLACES the tree; this one adds to it.
        """
        if not self._extra_clone_files:
            return
        for rel_path, content in self._extra_clone_files.items():
            target = dest / rel_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")

    def commit_push(self, workdir: Path, message: str) -> bool:
        self.calls.append(f"commit_push:{message}")
        self.pushes.append((workdir, message))
        self._pushed_trees.append(
            {
                p.relative_to(workdir).as_posix(): p.read_bytes()
                for p in workdir.rglob("*")
                if p.is_file()
            }
        )
        result = self._commit_push_results[
            min(self._commit_push_index, len(self._commit_push_results) - 1)
        ]
        if self._commit_push_index < len(self._commit_push_results) - 1:
            self._commit_push_index += 1
        return result

    def pushed_file(self, relpath: str) -> str:
        """Content of `relpath` in the most recent `commit_push`'s workdir
        tree, decoded as UTF-8 text (marketplace repo door, Task 1) -- see
        the class docstring's `clone_tree` entry. Raises `AssertionError`
        if `commit_push` was never called, or if its tree never held that
        path -- a test asserting on the wrong path fails loudly rather than
        silently reading something misleading.
        """
        assert self._pushed_trees, "commit_push was never called"
        tree = self._pushed_trees[-1]
        assert relpath in tree, f"{relpath!r} was not pushed (pushed: {sorted(tree)})"
        return tree[relpath].decode("utf-8")

    @property
    def push_count(self) -> int:
        """How many times `commit_push` has been called (marketplace repo
        door, Task 1) -- e.g. a validate-then-commit ordering assertion
        that nothing was pushed after a validation failure."""
        return len(self.pushes)

    def open_pr(self, workdir: Path, *, repo: str, branch: str, title: str, body: str) -> str:
        """Records the exact call (`open_pr_calls`, one dict per call) and
        returns the fixed `pr_url` the fake was constructed with — no real
        `git`/`gh` subprocess involved. Also snapshots `workdir`'s current
        content the same way `create_repo_from_dir` does (see
        `_snapshot_pushed_content`) when `track_pushed_content=True` — a
        later `clone()` of `repo` then reflects the PR's content, letting a
        test inspect what was pushed via the same public `clone()` seam
        rather than reaching into a caller's own (possibly by-then-deleted)
        `workdir`.

        Also registers `pr_url` into the `find_pr` map under this exact
        `repo`/`branch` pair (see `open_prs` on the class docstring) — a
        second call against the same fake (run 2 of bootstrap, say) sees the
        PR `find_pr` reports as already open, without a test needing to
        configure `open_prs` by hand.
        """
        self.calls.append(f"open_pr:{repo}:{branch}")
        self.open_pr_calls.append(
            {"workdir": workdir, "repo": repo, "branch": branch, "title": title, "body": body}
        )
        self._snapshot_pushed_content(repo, workdir)
        self._open_prs[f"{repo}#{branch}"] = self._pr_url
        self._existing_branches.add(f"{repo}#{branch}")
        return self._pr_url

    def find_pr(self, repo: str, *, branch: str) -> str | None:
        self.calls.append(f"find_pr:{repo}:{branch}")
        return self._open_prs.get(f"{repo}#{branch}")

    def compare(self, repo: str, base: str, head: str) -> BranchComparison:
        """Whatever `comparisons` holds for `head`, else a comparison that
        touches `gojira.yaml` alone under the room's own commit identity --
        the wired happy path, so a test only configures this when it is
        modelling a branch somebody ELSE made.

        A branch named in neither `comparisons` nor `existing_branches`
        answers `found=False`, the real client's "either ref is gone".
        """
        self.calls.append(f"compare:{repo}:{base}...{head}")
        if head in self._comparisons:
            return self._comparisons[head]
        if f"{repo}#{head}" not in self._existing_branches:
            return BranchComparison(found=False, files=(), authors=())
        return BranchComparison(
            found=True, files=("gojira.yaml",), authors=(COMMIT_AUTHOR_EMAIL,)
        )

    def delete_branch(self, repo: str, branch: str) -> bool:
        """Forget `repo#branch` (and anything `branch_files` held for it),
        recording the call. True when it was there, False when it was not
        -- the real client's already-gone answer.
        """
        self.calls.append(f"delete_branch:{repo}:{branch}")
        self.deleted_branches.append((repo, branch))
        self._branch_files.pop(branch, None)
        key = f"{repo}#{branch}"
        if key in self._existing_branches:
            self._existing_branches.discard(key)
            return True
        return False

    def branch_exists(self, repo: str, branch: str) -> bool:
        """True for any `repo#branch` named in `existing_branches`. Default
        empty: a repository with no leftover branches is the wired happy
        path, same convention as every other knob here.

        `open_pr` registers its own branch here too, so a second call
        against the same fake sees the branch that call pushed -- which is
        what the real repository would show.
        """
        self.calls.append(f"branch_exists:{repo}:{branch}")
        return f"{repo}#{branch}" in self._existing_branches

    def close_pr(self, repo: str, pr_url: str, comment: str) -> None:
        """Records `(repo, pr_url, comment)` into `close_pr_calls` and
        forgets the pull request, so a later `find_pr` for the branch it
        was open on answers None -- what the real repository would say."""
        self.calls.append(f"close_pr:{repo}:{pr_url}")
        self.close_pr_calls.append((repo, pr_url, comment))
        for key, url in list(self._open_prs.items()):
            if key.startswith(f"{repo}#") and url == pr_url:
                del self._open_prs[key]

    def merge_pr(self, repo: str, pr_url: str) -> bool:
        """Records `(repo, pr_url)` into `merge_pr_calls` and replays
        `merge_pr_results` (holding at the last entry once exhausted, same
        convention as `commit_push_results`). Default True: the room's own
        wiring pull request merges, which is the wired happy path. False is
        how a test models GitHub declining (a protected branch, a required
        review) -- never an exception, since the real client answers False
        there rather than raising.
        """
        self.calls.append(f"merge_pr:{repo}:{pr_url}")
        self.merge_pr_calls.append((repo, pr_url))
        result = self._merge_pr_results[
            min(self._merge_pr_index, len(self._merge_pr_results) - 1)
        ]
        if self._merge_pr_index < len(self._merge_pr_results) - 1:
            self._merge_pr_index += 1
        return result

    def local_head(self, workdir: Path) -> str:
        self.calls.append(f"local_head:{workdir}")
        self.local_head_calls.append(workdir)
        return self._local_head_result

    def head_sha(self, repo: str) -> str:
        self.calls.append(f"head_sha:{repo}")
        if self._head_sha_sequence is not None:
            index = min(self._head_sha_index, len(self._head_sha_sequence) - 1)
            if self._head_sha_index < len(self._head_sha_sequence) - 1:
                self._head_sha_index += 1
            return self._head_sha_sequence[index]
        return self._head_sha

    def latest_run(self, repo: str) -> dict | None:
        """Protocol parity for the build-log viewer: the newest run of the
        newest scripted sha, or None when nothing is scripted -- enough for
        the route's own tests, which bring their own richer fake."""
        self.calls.append(f"latest_run:{repo}")
        for runs in reversed(list(self._runs_by_sha.values())):
            if runs and runs[-1]:
                run = dict(runs[-1][-1])
                run.setdefault("head_sha", "")
                return run
        return None

    def run_log(self, repo: str, run_id: int, *, failed_only: bool = True) -> str:
        self.calls.append(f"run_log:{repo}:{run_id}:{failed_only}")
        return "fake log"

    def runs_for_commit(self, repo: str, sha: str) -> list[dict]:
        self.calls.append(f"runs_for_commit:{repo}:{sha}")
        sequence = self._runs_by_sha.get(sha, [[]])
        index = self._run_index_by_sha.get(sha, 0)
        poll_result = sequence[min(index, len(sequence) - 1)]
        if index < len(sequence) - 1:
            self._run_index_by_sha[sha] = index + 1
        for run in poll_result:
            self._run_id_to_sha[run["id"]] = sha
        return [dict(run) for run in poll_result]

    def run_jobs(self, repo: str, run_id: int) -> list[dict]:
        self.calls.append(f"run_jobs:{repo}:{run_id}")
        if self._run_jobs_error is not None:
            raise self._run_jobs_error
        return [dict(job) for job in self._jobs_by_run.get(run_id, [])]

    def rerun(self, repo: str, run_id: int) -> None:
        self.calls.append(f"rerun:{repo}:{run_id}")
        self.rerun_calls.append((repo, run_id))
        sha = self._run_id_to_sha.get(run_id)
        if sha is not None:
            if self._rerun_followup is not None:
                self._runs_by_sha[sha] = [
                    [{"id": run_id, **poll}] for poll in self._rerun_followup
                ]
            else:
                self._runs_by_sha[sha] = [[{"id": run_id, **self._rerun_result}]]
            self._run_index_by_sha[sha] = 0

    def commit_shas_for_paths(self, workdir: Path, paths: list[str]) -> dict[str, str]:
        self.calls.append(f"commit_shas_for_paths:{sorted(paths)}")
        return {
            path: self._intake_commit_shas.get(path, self._local_head_result) for path in paths
        }

    def is_ancestor(self, workdir: Path, ancestor: str, descendant: str) -> bool:
        self.calls.append(f"is_ancestor:{ancestor}:{descendant}")
        if ancestor == descendant:
            return True
        return (ancestor, descendant) in self._ancestor_pairs

    def rev_parse_prefix(self, workdir: Path, prefix: str) -> str | None:
        self.calls.append(f"rev_parse_prefix:{prefix}")
        if prefix in self._rev_parse_results:
            return self._rev_parse_results[prefix]
        if self._local_head_result.startswith(prefix):
            return self._local_head_result
        return None

    def rename_repo(self, repo: str, new_name: str) -> None:
        self.calls.append(f"rename_repo:{repo}:{new_name}")
        self.rename_calls.append((repo, new_name))
        if self._rename_error is not None:
            raise ClientError(self._rename_error)
        if repo not in self.repos:
            raise ClientError(f"repo not found: {repo}")
        owner = repo.rsplit("/", 1)[0]
        new_repo = f"{owner}/{new_name}"
        self.repos.discard(repo)
        self.repos.add(new_repo)
        self.renamed[repo] = new_repo

    def archive_repo(self, repo: str) -> None:
        self.calls.append(f"archive_repo:{repo}")
        self.archive_calls.append(repo)
        if self._archive_error is not None:
            raise ClientError(self._archive_error)
        if repo not in self.repos:
            raise ClientError(f"repo not found: {repo}")
        self.archived.add(repo)


