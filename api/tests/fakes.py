def _app_name_from_repo(repo: str) -> str:
    """"acme/agent-clio" -> "clio" (mirrors agent-<name> repo naming)."""
    return repo.rsplit("/", 1)[-1].removeprefix("agent-")


class FakeGitHub:
    """Records repo creation/clones/pushes. `clone` materializes a realistic
    generated-scaffolding tree at `dest` (see the module-level templates
    above); `commit_push` replays a configurable sequence of bool results, so
    a test can make a second call return False (nothing to commit) without
    any real git diffing.

    CI-run behavior is keyed by commit sha, mirroring the real
    `runs_for_commit(repo, sha)` (never a repo-wide "latest"): `runs_by_sha`
    maps a sha to a *sequence of polls*, each poll itself the list of run
    dicts `runs_for_commit` would return that time (an empty list models CI
    registration lag — no run yet for that commit). Each sha's sequence holds
    at its last entry once exhausted, same replay convention as
    `commit_push_results`. `head_sha` answers with the fixed `head_sha` the
    fake was constructed with, unless `head_sha_sequence` is given, in which
    case each call returns the next entry (holding at the last one once
    exhausted — same replay convention as everything else here). BuildStep
    now resolves head_sha fresh on every poll (Fix 2: following an
    advancing head rather than pinning a stale read), so
    `head_sha_sequence` is how a test simulates the platform's setup-PR
    merge landing mid-poll — e.g. `["sha1", "sha1", "sha2"]` models two
    polls still seeing the pre-merge commit before the third sees the
    merge commit as head.

    `rerun(repo, run_id)` mirrors gh's real behavior of reusing the run's id
    rather than minting a new one: it records the call in `rerun_calls` and
    replaces whichever sha that run_id was last seen under with a fresh
    poll sequence, so a test can control what BuildStep sees on the polls
    right after the rerun fires. By default that's a single held-forever
    poll built from `rerun_result` (default a completed success) — enough
    for the plain heal case, or configure `rerun_result` to fail again to
    exercise the double-failure path. `rerun_followup`, when given, models a
    multi-poll sequence instead (one dict per poll, each merged with the run
    id, holding at the last entry once exhausted) — this is how a test
    simulates gh's read-after-write lag still echoing the stale pre-rerun
    payload for a poll or two before the real post-rerun result (e.g.
    queued, then completed) shows up.

    `knowledge_files` (P2b), when given, is a `{filename: content}` map that
    `clone` also materializes, under `bundle/knowledge/`, alongside the
    generated scaffolding above — this is how a test puts existing seed-memory
    files in the cloned repo for `pnyx_api.knowledge.read_knowledge` (and
    friends) to find. Defaults to `None`, in which case `clone` writes no
    `bundle/knowledge/` tree at all (matching a real agent repo that has none
    yet) — every test that constructs a bare `FakeGitHub()` is unaffected by
    this knob's addition. `local_head_result` (P2b) is the fixed value
    `local_head(workdir)` returns — a real 40-hex sha shape by default,
    consistent with `FakeKubectl`'s default `deploy_image` tag (see
    `FAKE_LOCAL_HEAD_DEFAULT`/`FAKE_DEPLOY_IMAGE_DEFAULT` above) so the two
    fakes wired together read as "delivered" out of the box. Every call is
    recorded in both `calls` and the dedicated `local_head_calls` (the exact
    `workdir` it was given), so a test can assert it was called with the same
    workdir `commit_push` saw.

    `agent_yaml_transports` (P2c), when given, makes `clone` also write
    `bundle/agent.yaml` with `transports` set to exactly that list — the
    fixture `pnyx_api.slack_setup.wire_slack`'s tests edit. Defaults to
    `None`, in which case `clone` writes no `bundle/agent.yaml` at all —
    matching a real agent repo's shape closely enough for existing tests
    (which predate this knob and assert bare `FakeGitHub()` writes no
    `bundle/` tree at all) while leaving every one of them unaffected: pass
    e.g. `[{"kind": "a2a", "host": "0.0.0.0", "port": 8080}]` (matching
    `pnyx_api.composer`'s real rendering) for a wire_slack test that needs
    the file to exist. `gojira_secrets_from`, when given, adds a
    `secrets_from` key to the written `gojira.yaml` (absent by default,
    matching a real gojira.yaml that hasn't been through any
    `secrets_from`-writing edit yet) — the seam for testing that
    `wire_slack`'s edit appends to an existing list rather than clobbering
    it. `dockerfile_image`, defaulting to `FAKE_DOCKERFILE_OLD_IMAGE`, is the
    base image `clone` writes into a top-level `Dockerfile` (mirroring
    `pnyx_api.composer`'s real template) — always written, unlike the
    knobs above, since every real agent repo has had a Dockerfile since it
    was first composed; the runtime-bump fixture `wire_slack`'s
    `_update_dockerfile_runtime_image` edit rewrites the FROM line of.

    `org_yaml` (Task 2), when given, makes `clone` also write a top-level
    `org.yaml` with exactly that text — the fixture `pnyx_api.org.
    load_org_config`'s tests use to control what a cloned pnyx-config repo's
    org.yaml contains. Defaults to `None`, in which case `clone` writes no
    `org.yaml` at all (matching every other repo, none of which have ever
    had one). `clone_error`, when set, makes `clone` raise
    `ClientError(clone_error)` instead of writing anything — the seam for
    exercising a caller's clone-failure handling (e.g. `load_org_config`'s
    unwired-on-`ClientError` path) without a real git/gh subprocess. The
    call is still recorded in `.calls`/`.cloned` first, same as every other
    call here, before the error is raised.

    `track_pushed_content` (Task 7), when True, makes `create_repo_from_dir`
    snapshot every file under `src` (read at call time, before the caller's
    own tmpdir is cleaned up) into a per-repo store; `clone` for a repo with
    such a snapshot writes back exactly those files (nothing else — the
    synthetic gojira scaffolding below is skipped entirely for that repo)
    instead of synthesizing the generated-agent-repo tree. Defaults to
    `False`, so every pre-existing test (the whole agent-repo pipeline, whose
    `clone()` calls deliberately model "what gojira's own onboarding left in
    the repo", NOT a replay of whatever pnyx itself pushed) is unaffected —
    this is purely for Task 7's bootstrap, which pushes/clones repos (the
    org-config repo, an org's skills repo) gojira never touches at all, so a
    faithful "clone reflects exactly what was last pushed" model is the
    right one there instead. `pr_url`, `open_pr`'s canned return value
    (Task 7), and `open_pr_calls`, the exact-argument recording for it, are
    documented on `open_pr` itself below.

    `open_prs` (Task 7 live-incident fix), when given, seeds `find_pr`'s
    open-PR map: keys are `f"{repo}#{branch}"`, values the PR URL `find_pr`
    should report as already open for that repo/branch pair. Defaults to
    `None` (no PR open anywhere), so every pre-existing test — which
    predates `find_pr` entirely — is unaffected. `open_pr` itself also
    writes into this same map (keyed off the `repo`/`branch` it was called
    with, valued with the fake's own `pr_url`) the moment it's called, so a
    single fake run through bootstrap twice reproduces the incident shape
    exactly: run 1's `open_pr` registers the PR, and run 2's `find_pr` sees
    it there without either being configured explicitly.
    """

    def __init__(
        self,
        *,
        existing_repos: set[str] | None = None,
        commit_push_results: list[bool] | None = None,
        head_sha: str = "deadbeef",
        head_sha_sequence: list[str] | None = None,
        runs_by_sha: dict[str, list[list[dict]]] | None = None,
        rerun_result: dict | None = None,
        rerun_followup: list[dict] | None = None,
        knowledge_files: dict[str, str] | None = None,
        local_head_result: str = FAKE_LOCAL_HEAD_DEFAULT,
        agent_yaml_transports: list[dict] | None = None,
        gojira_secrets_from: list[str] | None = None,
        dockerfile_image: str = FAKE_DOCKERFILE_OLD_IMAGE,
        org_yaml: str | None = None,
        clone_error: str | None = None,
        track_pushed_content: bool = False,
        pr_url: str = "https://github.com/acme-corp/example-org-skills/pull/1",
        open_prs: dict[str, str] | None = None,
    ):
        self.repos: set[str] = set(existing_repos) if existing_repos else set()
        self.created_from_dir: list[tuple[str, Path]] = []
        self.cloned: list[tuple[str, Path]] = []
        self.pushes: list[tuple[Path, str]] = []
        self.calls: list[str] = []
        self._track_pushed_content = track_pushed_content
        self._pushed_content: dict[str, dict[str, bytes]] = {}
        self._pr_url = pr_url
        self.open_pr_calls: list[dict] = []
        self._open_prs: dict[str, str] = dict(open_prs) if open_prs else {}
        self._commit_push_results = list(commit_push_results) if commit_push_results else [True]
        self._commit_push_index = 0
        self._knowledge_files = dict(knowledge_files) if knowledge_files else None
        self._local_head_result = local_head_result
        self._agent_yaml_transports = (
            list(agent_yaml_transports) if agent_yaml_transports is not None else None
        )
        self._gojira_secrets_from = (
            list(gojira_secrets_from) if gojira_secrets_from is not None else None
        )
        self._dockerfile_image = dockerfile_image
        self._org_yaml = org_yaml
        self._clone_error = clone_error
        self.local_head_calls: list[Path] = []

        self._head_sha = head_sha
        self._head_sha_sequence = list(head_sha_sequence) if head_sha_sequence else None
        self._head_sha_index = 0
        self._runs_by_sha: dict[str, list[list[dict]]] = {
            sha: [list(poll) for poll in sequence]
            for sha, sequence in (runs_by_sha or {}).items()
        }
        if not self._runs_by_sha:
            # Default: the fake's own head_sha already has one CI run that's
            # completed successfully — the plain happy path.
            self._runs_by_sha[head_sha] = [
                [{"id": 1, "status": "completed", "conclusion": "success"}]
            ]
        self._run_index_by_sha: dict[str, int] = {}
        self._run_id_to_sha: dict[int, str] = {}
        self._rerun_result = rerun_result or {"status": "completed", "conclusion": "success"}
        self._rerun_followup = list(rerun_followup) if rerun_followup else None
        self.rerun_calls: list[tuple[str, int]] = []

    def repo_exists(self, repo: str) -> bool:
        self.calls.append(f"repo_exists:{repo}")
        return repo in self.repos

    def _snapshot_pushed_content(self, repo: str, src: Path) -> None:
        """Read every file under `src` now, synchronously — the real
        caller's tmpdir (Task 7's bootstrap, notably) is typically deleted
        the moment the call that invoked this returns, so this is the only
        chance to snapshot what was actually pushed. No-op unless the fake
        was constructed with `track_pushed_content=True`.
        """
        if not self._track_pushed_content:
            return
        self._pushed_content[repo] = {
            p.relative_to(src).as_posix(): p.read_bytes() for p in src.rglob("*") if p.is_file()
        }

    def create_repo_from_dir(self, repo: str, src: Path) -> None:
        self.calls.append(f"create_repo_from_dir:{repo}")
        self.created_from_dir.append((repo, src))
        self.repos.add(repo)
        self._snapshot_pushed_content(repo, src)

    def clone(self, repo: str, dest: Path) -> None:
        self.calls.append(f"clone:{repo}")
        self.cloned.append((repo, dest))
        if self._clone_error is not None:
            raise ClientError(self._clone_error)

        if repo in self._pushed_content:
            # A repo tracked via `track_pushed_content`: model this clone as
            # exactly what was last pushed to it, nothing more — the generic
            # generated-agent-repo scaffolding below deliberately does not
            # apply (see the class docstring).
            for rel_path, data in self._pushed_content[repo].items():
                target = dest / rel_path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
            return

        name = _app_name_from_repo(repo)
        base = dest / "k8s" / "base"
        base.mkdir(parents=True, exist_ok=True)

        gojira_yaml_text = GOJIRA_YAML_TEMPLATE.format(name=name)
        if self._gojira_secrets_from is not None:
            gojira_data = yaml.safe_load(gojira_yaml_text)
            gojira_data["secrets_from"] = list(self._gojira_secrets_from)
            gojira_yaml_text = yaml.safe_dump(gojira_data, sort_keys=False)
        (dest / "gojira.yaml").write_text(gojira_yaml_text)

        (base / "deployment.yaml").write_text(DEPLOYMENT_YAML_TEMPLATE.format(name=name))
        (base / "service.yaml").write_text(SERVICE_YAML_TEMPLATE.format(name=name))
        (base / "podmonitoring.yaml").write_text(PODMONITORING_YAML_TEMPLATE.format(name=name))
        (base / "rules.yaml").write_text(RULES_YAML_TEMPLATE.format(name=name))
        (base / "kustomization.yaml").write_text(KUSTOMIZATION_YAML_TEMPLATE.format(name=name))

        (dest / "Dockerfile").write_text(DOCKERFILE_TEMPLATE.format(image=self._dockerfile_image))

        if self._org_yaml is not None:
            (dest / "org.yaml").write_text(self._org_yaml)

        bundle_dir = dest / "bundle"
        if self._agent_yaml_transports is not None:
            bundle_dir.mkdir(parents=True, exist_ok=True)
            agent_yaml_data = {"name": name, "transports": list(self._agent_yaml_transports)}
            (bundle_dir / "agent.yaml").write_text(
                yaml.safe_dump(agent_yaml_data, sort_keys=False)
            )

        if self._knowledge_files:
            knowledge_dir = bundle_dir / "knowledge"
            knowledge_dir.mkdir(parents=True, exist_ok=True)
            for filename, content in self._knowledge_files.items():
                (knowledge_dir / filename).write_text(content)

    def commit_push(self, workdir: Path, message: str) -> bool:
        self.calls.append(f"commit_push:{message}")
        self.pushes.append((workdir, message))
        result = self._commit_push_results[
            min(self._commit_push_index, len(self._commit_push_results) - 1)
        ]
        if self._commit_push_index < len(self._commit_push_results) - 1:
            self._commit_push_index += 1
        return result

    def open_pr(self, workdir: Path, *, repo: str, branch: str, title: str, body: str) -> str:
        """Records the exact call (`open_pr_calls`, one dict per call) and
        returns the fixed `pr_url` the fake was constructed with — no real
        `git`/`gh` subprocess involved. Also snapshots `workdir`'s current
        content the same way `create_repo_from_dir` does (see
        `_snapshot_pushed_content`) when `track_pushed_content=True` — a
        later `clone()` of `repo` then reflects the PR's content, letting a
        test inspect what was pushed via the same public `clone()` seam
        rather than reaching into a caller's own (possibly by-then-deleted)
        `workdir`.

        Also registers `pr_url` into the `find_pr` map under this exact
        `repo`/`branch` pair (see `open_prs` on the class docstring) — a
        second call against the same fake (run 2 of bootstrap, say) sees the
        PR `find_pr` reports as already open, without a test needing to
        configure `open_prs` by hand.
        """
        self.calls.append(f"open_pr:{repo}:{branch}")
        self.open_pr_calls.append(
            {"workdir": workdir, "repo": repo, "branch": branch, "title": title, "body": body}
        )
        self._snapshot_pushed_content(repo, workdir)
        self._open_prs[f"{repo}#{branch}"] = self._pr_url
        return self._pr_url

    def find_pr(self, repo: str, *, branch: str) -> str | None:
        self.calls.append(f"find_pr:{repo}:{branch}")
        return self._open_prs.get(f"{repo}#{branch}")

    def local_head(self, workdir: Path) -> str:
        self.calls.append(f"local_head:{workdir}")
        self.local_head_calls.append(workdir)
        return self._local_head_result

    def head_sha(self, repo: str) -> str:
        self.calls.append(f"head_sha:{repo}")
        if self._head_sha_sequence is not None:
            index = min(self._head_sha_index, len(self._head_sha_sequence) - 1)
            if self._head_sha_index < len(self._head_sha_sequence) - 1:
                self._head_sha_index += 1
            return self._head_sha_sequence[index]
        return self._head_sha

    def runs_for_commit(self, repo: str, sha: str) -> list[dict]:
        self.calls.append(f"runs_for_commit:{repo}:{sha}")
        sequence = self._runs_by_sha.get(sha, [[]])
        index = self._run_index_by_sha.get(sha, 0)
        poll_result = sequence[min(index, len(sequence) - 1)]
        if index < len(sequence) - 1:
            self._run_index_by_sha[sha] = index + 1
        for run in poll_result:
            self._run_id_to_sha[run["id"]] = sha
        return [dict(run) for run in poll_result]

    def rerun(self, repo: str, run_id: int) -> None:
        self.calls.append(f"rerun:{repo}:{run_id}")
        self.rerun_calls.append((repo, run_id))
        sha = self._run_id_to_sha.get(run_id)
        if sha is not None:
            if self._rerun_followup is not None:
                self._runs_by_sha[sha] = [
                    [{"id": run_id, **poll}] for poll in self._rerun_followup
                ]
            else:
                self._runs_by_sha[sha] = [[{"id": run_id, **self._rerun_result}]]
            self._run_index_by_sha[sha] = 0


class FakeGojira:
    """Walks a created app from "pending" to `end_status` on the
    `activate_after`-th status poll; records reprovision calls; can simulate a
    409 conflict on create for repos named in `conflict_repos`.

    `ping_result` (Task 8, org status's deploy-platform check) is the fixed
    bool `ping()` returns — defaults to True (the wired-happy-path), same
    knob idiom as every other fake's canned-result/error switches here: a
    test flips it to False to exercise the check's "can't reach the deploy
    platform" branch without a real gojira backend.
    """

    def __init__(
        self,
        *,
        activate_after: int = 1,
        end_status: str = "active",
        conflict_repos: set[str] | None = None,
        failed_steps: list[dict] | None = None,
        ping_result: bool = True,
    ):
        self._activate_after = activate_after
        self._end_status = end_status
        self._conflict_repos = set(conflict_repos) if conflict_repos else set()
        self._failed_steps = list(failed_steps) if failed_steps else []
        self._ping_result = ping_result
        self._apps: dict[int, dict] = {}
        self._next_id = 1
        self.reprovision_calls: list[int] = []
        self.calls: list[str] = []

    def create_app(self, *, name, repo_full_name, cluster, namespace) -> int:
        self.calls.append(f"create_app:{repo_full_name}")
        if repo_full_name in self._conflict_repos:
            raise GojiraConflict(f"app already connected for {repo_full_name!r}")
        app_id = self._next_id
        self._next_id += 1
        self._apps[app_id] = {
            "id": app_id,
            "name": name,
            "repo_full_name": repo_full_name,
            "cluster": cluster,
            "namespace": namespace,
            "status": "pending",
            "polls": 0,
            "setup_pr_url": None,
            "auto_merge_setup_pr": True,
            "steps": [],
        }
        return app_id

    def app_status(self, app_id: int) -> dict:
        self.calls.append(f"app_status:{app_id}")
        app = self._apps[app_id]
        app["polls"] += 1
        if app["status"] == "pending" and app["polls"] >= self._activate_after:
            app["status"] = self._end_status
        if app["status"] == "failed":
            app["steps"] = list(self._failed_steps)
        return dict(app)

    def reprovision(self, app_id: int) -> None:
        self.calls.append(f"reprovision:{app_id}")
        self.reprovision_calls.append(app_id)
        app = self._apps[app_id]
        app["status"] = "pending"
        app["polls"] = 0

    def ping(self) -> bool:
        self.calls.append("ping")
        return self._ping_result


